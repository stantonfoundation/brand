// Checks every color pair in tokens/contrast.json against the WCAG 2
// ratio it needs, computed from tokens/tokens.json, and checks that the
// contrast table in guidelines/color.md matches.
//
// Usage:
//   node scripts/check-contrast.mjs          check; exit 1 on a failure or a stale table
//   node scripts/check-contrast.mjs --write  rewrite the table in guidelines/color.md
//   pnpm contrast                            the same, then align it with Prettier
import { readFileSync, writeFileSync } from "node:fs";

const repo = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, repo), "utf8");

const colors = JSON.parse(read("tokens/tokens.json")).color;
const { pairs } = JSON.parse(read("tokens/contrast.json"));

const hex = (name) => {
  const token = colors[name];
  if (!token)
    throw new Error(`tokens/contrast.json names unknown color "${name}"`);
  return token.$value;
};

// WCAG 2 relative luminance and contrast ratio.
const luminance = (value) => {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(value.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (fg, bg) => {
  const [hi, lo] = [luminance(hex(fg)), luminance(hex(bg))].sort(
    (a, b) => b - a,
  );
  return (hi + 0.05) / (lo + 0.05);
};

// Round down, so a pair never shows as passing when it does not.
const floor2 = (n) => Math.floor(n * 100) / 100;

const results = pairs.map((p) => ({ ...p, ratio: floor2(ratio(p.fg, p.bg)) }));

const failures = results.filter((r) => r.ratio < r.min);

const verdict = (r) => {
  if (r.ratio < r.min) return `Fails (needs ${r.min}:1)`;
  if (r.min === 3) return "Passes 3:1";
  return r.ratio >= 7 ? "AAA" : "AA";
};

const table = [
  "| Foreground on ground | Use | Ratio | Result |",
  "| --- | --- | --- | --- |",
  ...results.map(
    (r) =>
      `| ${r.fg} on ${r.bg} | ${r.use} | ${r.ratio.toFixed(2)} | ${verdict(r)} |`,
  ),
].join("\n");

const START =
  "<!-- contrast-table:start (generated by scripts/check-contrast.mjs) -->";
const END = "<!-- contrast-table:end -->";
const doc = read("guidelines/color.md");
const [before, rest] = doc.split(START);
if (rest === undefined || !rest.includes(END)) {
  console.error(`guidelines/color.md is missing the ${START} … ${END} markers`);
  process.exit(1);
}
const after = rest.slice(rest.indexOf(END) + END.length);
const current = rest.slice(0, rest.indexOf(END)).trim();

if (process.argv.includes("--write")) {
  writeFileSync(
    new URL("guidelines/color.md", repo),
    `${before}${START}\n\n${table}\n\n${END}${after}`,
  );
  console.log("guidelines/color.md: contrast table written.");
  process.exit(0);
}

const errors = [];
for (const r of failures) {
  errors.push(
    `${r.fg} on ${r.bg}: ${r.ratio.toFixed(2)}:1, needs ${r.min}:1 (${r.use})`,
  );
}
// Compare ignoring column padding, which Prettier owns.
const squash = (s) =>
  s
    .replace(/ *\| */g, "|")
    .replace(/-+/g, "-")
    .trim();
if (squash(current) !== squash(table)) {
  errors.push(
    "The contrast table in guidelines/color.md is out of date. Run: pnpm contrast",
  );
}

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}
console.log(`contrast ok: ${results.length} pairs`);
